void Ringbuffer_clear(tRingbuffer *rb)
{
    rb->count = 0;
    rb->oldest = 0;
}


bool Ringbuffer_push(tRingbuffer *rb, void *element)
{
    if(rb->count < rb->length)
    {
        int pos = rb->oldest + rb->count;
        if(pos >= rb->length)
        {
            pos -= rb->length;
        }
        rb->data[pos] = element;
        rb->count++;
        return true;
    }
    else
    {
        return false;
    }
}

bool Ringbuffer_pop(tRingbuffer *rb, void **element)
{
    if(rb->count == 0)
    {
        return false;
    }
    else
    {
        *element = rb->data[rb->oldest++];
        if (rb->oldest >= rb->length)
        {
            rb->oldest -= rb->length;
        }
        rb->count--;
        return true;
    }
}

bool Ringbuffer_peek(tRingbuffer *rb, void **element)
{
    if(rb->count == 0)
    {
        return false;
    }
    else
    {
        *element = rb->data[rb->oldest];
        return true;
    }
}


bool Ringbuffer_is_empty(tRingbuffer *rb)
{
    return rb->count == 0;
}


bool Ringbuffer_is_full(tRingbuffer *rb)
{
    return rb->count == rb->length;
}
