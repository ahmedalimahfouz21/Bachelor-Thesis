#ifndef RINGBUFFER_H
#define RINGBUFFER_H

//----------------------------------------------------------------------------------------------------------------------
// Include
//----------------------------------------------------------------------------------------------------------------------
#include <stdbool.h>


//----------------------------------------------------------------------------------------------------------------------
// Macros
//----------------------------------------------------------------------------------------------------------------------
#define RINGBUFFER_DECLARE(name, length) \
    void *name##__rbdata[(length)]; \
    tRingbuffer name = { 0, 0, (length), name##__rbdata };

//----------------------------------------------------------------------------------------------------------------------
// Types
//----------------------------------------------------------------------------------------------------------------------
typedef struct
{
    int oldest;
    int count;
    int length;
    void **data;
} tRingbuffer;


//----------------------------------------------------------------------------------------------------------------------
// Data
//----------------------------------------------------------------------------------------------------------------------



//----------------------------------------------------------------------------------------------------------------------
// Function prototypes
//----------------------------------------------------------------------------------------------------------------------
extern void Ringbuffer_clear(tRingbuffer *rb);
extern bool Ringbuffer_push(tRingbuffer *rb, void *element);
extern bool Ringbuffer_pop(tRingbuffer *rb, void **element);
extern bool Ringbuffer_peek(tRingbuffer *rb, void **element);
extern bool Ringbuffer_is_empty(tRingbuffer *rb);
extern bool Ringbuffer_is_full(tRingbuffer *rb);

#endif
