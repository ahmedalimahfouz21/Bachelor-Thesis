void Vt100SetInputBlocking()
{
    int flags = fcntl(STDIN_FILENO, F_GETFL);
    flags &= ~O_NONBLOCK;
    fcntl(STDIN_FILENO, F_SETFL, flags);
}


void Vt100SetInputNonBlocking()
{
    int flags = fcntl(STDIN_FILENO, F_GETFL);
    flags |= O_NONBLOCK;
    fcntl(STDIN_FILENO, F_SETFL, flags);
}

void Vt100SetCursor(int row, int column)
{
    printf("\033[%d;%df", row, column);
}
